const FONT_W = 6; // advance incl. 1px spacing
const FONT_H = 7;

function normalizeText(str) {
  let out = '';
  for (const ch of String(str)) {
    if (ch === 'v' || ch === 'x') { out += ch; continue; } // special glyphs
    const up = ch.toUpperCase();
    out += GLYPHS[up] ? up : (GLYPHS[ch] ? ch : '?');
  }
  return out;
}

function textWidth(str, scale = 1) {
  const s = normalizeText(str);
  return s.length ? (s.length * FONT_W - 1) * scale : 0;
}

// align: 'left' | 'center' | 'right'
function drawText(ctx, str, x, y, color = '#fff', opts = {}) {
  const scale = opts.scale || 1;
  const s = normalizeText(str);
  const w = textWidth(str, scale);
  if (opts.align === 'center') x -= Math.floor(w / 2);
  else if (opts.align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  if (opts.shadow) {
    drawTextRaw(ctx, s, x + scale, y + scale, opts.shadow, scale);
  }
  drawTextRaw(ctx, s, x, y, color, scale);
}

function drawTextRaw(ctx, s, x, y, color, scale) {
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const g = GLYPHS[s[i]];
    const ox = x + i * FONT_W * scale;
    for (let r = 0; r < FONT_H; r++) {
      const row = g[r];
      for (let c = 0; c < 5; c++) {
        if (row[c] === '#') ctx.fillRect(ox + c * scale, y + r * scale, scale, scale);
      }
    }
  }
}
